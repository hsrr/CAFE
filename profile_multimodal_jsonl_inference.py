def main() -> None:
    args = parse_args()
    ensure_runtime_dependencies()
    validate_paths(args)
    device = torch.device(args.device)

    dataset, dataset_mode = build_dataset(args)
    if len(dataset) == 0:
        raise ValueError("Dataset is empty. Check --ann-path and the jsonl contents.")
    loader = build_loader(dataset, args)
    first_batch = next(iter(loader))
    sample_inputs = (
        first_batch["input_ids"][:1].to(device),
        first_batch["attention_mask"][:1].to(device),
        first_batch["pixel_values"][:1].to(device),
    )

    model = build_model(args, device)
    weight_loading = load_model_weights(model, args)

    report = {
        "setup": {
            "device": str(device),
            "dataset_mode": dataset_mode,
            "num_classes": args.num_classes,
            "ann_path": args.ann_path,
            "image_root": args.image_root,
            "text_source": args.text_source,
            "batch_size": args.batch_size,
            "warmup_steps": args.warmup_steps,
            "single_sample_steps": args.single_sample_steps,
            "max_batches": args.max_batches,
        },
        "weight_loading": weight_loading,
        "parameters": count_parameters(model),
        "compute_cost": profile_compute_cost(model, sample_inputs, args.flops_backend),
        "single_sample_forward_latency_ms": benchmark_single_sample_forward_latency(
            model=model,
            sample_inputs=sample_inputs,
            device=device,
            warmup_steps=args.warmup_steps,
            measure_steps=args.single_sample_steps,
        ),
        "throughput_and_batch_latency": benchmark_throughput_and_batch_latency(
            model=model,
            loader=loader,
            device=device,
            max_batches=args.max_batches,
        ),
    }
    report["vram_memory_peak"] = report["throughput_and_batch_latency"]["cuda_memory_peak"]

    print_report(report)

    if args.output_json:
        output_path = Path(args.output_json)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
