def ensure_runtime_dependencies() -> None:
    missing = []
    if AutoModel is None or AutoTokenizer is None:
        missing.append("transformers")
    if transforms is None or resnet34 is None or InterpolationMode is None:
        missing.append("torchvision")
    if missing:
        raise ImportError("Missing runtime dependencies: " + ", ".join(missing))


def validate_paths(args: argparse.Namespace) -> None:
    if args.ann_path and not Path(args.ann_path).exists():
        raise FileNotFoundError(f"Annotation file not found: {args.ann_path}")
    if args.image_root and not Path(args.image_root).exists():
        raise FileNotFoundError(f"Image root not found: {args.image_root}")
    if args.resnet34_weights_path:
        weight_path = Path(args.resnet34_weights_path)
        if not weight_path.exists():
            raise FileNotFoundError(f"ResNet-34 weights file not found: {args.resnet34_weights_path}")


def is_tensor_state_dict(candidate: Any) -> bool:
    return isinstance(candidate, dict) and candidate and all(torch.is_tensor(v) for v in candidate.values())


def strip_module_prefix(state_dict: Dict[str, Any]) -> Dict[str, Any]:
    return {
        key.replace("module.", "", 1) if key.startswith("module.") else key: value
        for key, value in state_dict.items()
    }


def extract_state_dict(checkpoint_obj: Any) -> Dict[str, Any]:
    if is_tensor_state_dict(checkpoint_obj):
        return strip_module_prefix(checkpoint_obj)

    if isinstance(checkpoint_obj, dict):
        for key in ("state_dict", "model_state_dict", "model", "network", "module"):
            candidate = checkpoint_obj.get(key)
            if is_tensor_state_dict(candidate):
                return strip_module_prefix(candidate)

    raise ValueError("Unable to locate a valid state_dict in the checkpoint.")


def load_state_dict_report(module: nn.Module, state_dict: Dict[str, Any], strict: bool) -> Dict[str, Any]:
    incompatible = module.load_state_dict(state_dict, strict=strict)
    return {
        "missing_keys": list(incompatible.missing_keys),
        "unexpected_keys": list(incompatible.unexpected_keys),
    }


def load_checkpoint_with_report(module: nn.Module, checkpoint_path: str, strict: bool) -> Dict[str, Any]:
    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    report = load_state_dict_report(module, extract_state_dict(checkpoint), strict=strict)
    report["path"] = checkpoint_path
    return report


def load_model_weights(model: EndToEndCAFEWithEncoders, args: argparse.Namespace) -> Dict[str, Any]:
    reports: Dict[str, Any] = {
        "strict_load": args.strict_load,
        "loaded": [],
        "encoder_sources": {
            "text_encoder_name_or_path": args.text_encoder_name_or_path,
            "image_encoder": (
                args.resnet34_weights_path
                if args.resnet34_weights_path
                else (
                    "resnet34-imagenet"
                    if not args.disable_pretrained_image_encoder
                    else "resnet34-random-init"
                )
            ),
        },
    }

    if args.checkpoint:
        checkpoint = torch.load(args.checkpoint, map_location="cpu")
        nested_keys = (
            "text_encoder",
            "image_encoder",
            "text_projector",
            "similarity_module",
            "detection_module",
        )
        if isinstance(checkpoint, dict) and any(key in checkpoint for key in nested_keys):
            component_reports: Dict[str, Any] = {"type": "checkpoint:nested_modules", "path": args.checkpoint}
            for key in nested_keys:
                if key in checkpoint:
                    component_reports[key] = load_state_dict_report(
                        getattr(model, key),
                        extract_state_dict(checkpoint[key]),
                        strict=args.strict_load,
                    )
            reports["loaded"].append(component_reports)
        else:
            reports["loaded"].append(
                {
                    "type": "checkpoint:wrapped_model",
                    **load_checkpoint_with_report(model, args.checkpoint, strict=args.strict_load),
                }
            )

    component_paths = {
        "text_encoder": args.text_encoder_checkpoint,
        "image_encoder": args.image_encoder_checkpoint,
        "text_projector": args.text_projector_checkpoint,
        "similarity_module": args.similarity_checkpoint,
        "detection_module": args.detection_checkpoint,
    }
    for name, checkpoint_path in component_paths.items():
        if checkpoint_path:
            reports["loaded"].append(
                {
                    "type": f"checkpoint:{name}",
                    **load_checkpoint_with_report(getattr(model, name), checkpoint_path, strict=args.strict_load),
                }
            )

    return reports


def build_model(args: argparse.Namespace, device: torch.device) -> EndToEndCAFEWithEncoders:
    model = EndToEndCAFEWithEncoders(
        text_encoder_name_or_path=args.text_encoder_name_or_path,
        num_classes=args.num_classes,
        use_pretrained_image_encoder=not args.disable_pretrained_image_encoder,
        image_encoder_weights_path=args.resnet34_weights_path,
        image_normalization=args.image_normalization,
    )
    model.to(device)
    model.eval()
    return model


def build_dataset(args: argparse.Namespace) -> Tuple[Dataset, str]:
    if args.ann_path and args.image_root:
        return (
            JsonlImagePromptDataset(
                ann_path=args.ann_path,
                image_root=args.image_root,
                image_extension=args.image_extension,
                max_words=args.max_words,
                text_source=args.text_source,
                label_map_mode=args.label_map_mode,
            ),
            "jsonl_image_prompt",
        )

    return SyntheticRawDataset(num_samples=args.synthetic_samples, num_classes=args.num_classes), "synthetic"


def build_loader(dataset: Dataset, args: argparse.Namespace) -> DataLoader:
    tokenizer = AutoTokenizer.from_pretrained(args.text_encoder_name_or_path)
    collator = MultimodalBatchCollator(
        tokenizer=tokenizer,
        image_size=args.image_size,
        max_text_tokens=args.max_text_tokens,
        image_normalization=args.image_normalization,
    )
    return DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=torch.cuda.is_available(),
        collate_fn=collator,
    )


def count_parameters(model: nn.Module) -> Dict[str, int]:
    total = sum(parameter.numel() for parameter in model.parameters())
    trainable = sum(parameter.numel() for parameter in model.parameters() if parameter.requires_grad)
    return {
        "params_total": int(total),
        "params_trainable": int(trainable),
    }


def maybe_sync(device: torch.device) -> None:
    if device.type == "cuda":
        torch.cuda.synchronize(device)


def percentile(values: Sequence[float], q: float) -> float:
    if not values:
        return float("nan")
    return float(np.percentile(np.asarray(values, dtype=np.float64), q))


def summarize_ms(values_ms: Sequence[float]) -> Dict[str, float]:
    values = list(values_ms)
    if not values:
        return {
            "mean_ms": float("nan"),
            "std_ms": float("nan"),
            "p50_ms": float("nan"),
            "p90_ms": float("nan"),
            "p95_ms": float("nan"),
        }
    return {
        "mean_ms": float(statistics.mean(values)),
        "std_ms": float(statistics.pstdev(values)) if len(values) > 1 else 0.0,
        "p50_ms": percentile(values, 50),
        "p90_ms": percentile(values, 90),
        "p95_ms": percentile(values, 95),
    }


def current_cuda_memory(device: torch.device) -> Dict[str, Optional[float]]:
    if device.type != "cuda":
        return {
            "cuda_max_memory_allocated_mb": None,
            "cuda_max_memory_reserved_mb": None,
        }
    return {
        "cuda_max_memory_allocated_mb": float(torch.cuda.max_memory_allocated(device) / (1024 ** 2)),
        "cuda_max_memory_reserved_mb": float(torch.cuda.max_memory_reserved(device) / (1024 ** 2)),
    }


def make_forward_inputs(batch: Dict[str, Any]) -> Dict[str, torch.Tensor]:
    return {
        "input_ids": batch["input_ids"],
        "attention_mask": batch["attention_mask"],
        "pixel_values": batch["pixel_values"],
    }


def move_batch_to_device(batch: Dict[str, Any], device: torch.device) -> Dict[str, Any]:
    moved: Dict[str, Any] = {}
    for key, value in batch.items():
        if torch.is_tensor(value):
            moved[key] = value.to(device, non_blocking=True)
        else:
            moved[key] = value
    return moved


def profile_compute_cost(
    model: nn.Module,
    sample_inputs: Tuple[torch.Tensor, torch.Tensor, torch.Tensor],
    backend: str,
) -> Dict[str, Any]:
    selected_backend = backend
    if backend == "auto":
        if thop_profile is not None:
            selected_backend = "thop"
        elif FlopCountAnalysis is not None:
            selected_backend = "fvcore"
        else:
            selected_backend = "none"

    report = {
        "backend": selected_backend,
        "forward_macs": None,
        "forward_flops": None,
        "notes": [],
    }

    if selected_backend == "none":
        report["notes"].append("Install thop or fvcore to enable static compute analysis.")
        return report

    with torch.inference_mode():
        if selected_backend == "thop":
            macs, _ = thop_profile(model, inputs=sample_inputs, verbose=False)
            report["forward_macs"] = float(macs)
            report["forward_flops"] = float(macs * 2.0)
            report["notes"].append("FLOPs are reported as 2 x MACs under the thop convention.")
            return report

        if selected_backend == "fvcore":
            analysis = FlopCountAnalysis(model, sample_inputs)
            flops = analysis.total()
            report["forward_macs"] = float(flops)
            report["forward_flops"] = float(flops * 2.0)
            unsupported = analysis.unsupported_ops()
            if unsupported:
                report["notes"].append(
                    "Unsupported ops skipped by fvcore: "
                    + ", ".join(f"{name} x {count}" for name, count in unsupported.items())
                )
            report["notes"].append("FLOPs are approximated as 2 x fvcore-reported ops.")
            return report

    raise ValueError(f"Unsupported backend: {selected_backend}")


def benchmark_single_sample_forward_latency(
    model: nn.Module,
    sample_inputs: Tuple[torch.Tensor, torch.Tensor, torch.Tensor],
    device: torch.device,
    warmup_steps: int,
    measure_steps: int,
) -> Dict[str, Any]:
    timings_ms: List[float] = []

    if device.type == "cuda":
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats(device)

    with torch.inference_mode():
        for _ in range(max(warmup_steps, 0)):
            _ = model(*sample_inputs)
        maybe_sync(device)

        if device.type == "cuda":
            torch.cuda.reset_peak_memory_stats(device)

        for _ in range(max(measure_steps, 1)):
            maybe_sync(device)
            start = time.perf_counter()
            _ = model(*sample_inputs)
            maybe_sync(device)
            end = time.perf_counter()
            timings_ms.append((end - start) * 1000.0)

    metrics = summarize_ms(timings_ms)
    metrics.update(current_cuda_memory(device))
    return metrics


def benchmark_throughput_and_batch_latency(
    model: nn.Module,
    loader: DataLoader,
    device: torch.device,
    max_batches: int,
) -> Dict[str, Any]:
    forward_batch_latency_ms: List[float] = []
    e2e_batch_latency_ms: List[float] = []
    per_sample_forward_ms: List[float] = []
    total_samples = 0
    total_e2e_seconds = 0.0
    batches_measured = 0

    iterator = iter(loader)

    if device.type == "cuda":
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats(device)

    with torch.inference_mode():
        while True:
            if max_batches and batches_measured >= max_batches:
                break

            e2e_start = time.perf_counter()
            try:
                batch = next(iterator)
            except StopIteration:
                break

            batch = move_batch_to_device(batch, device)
            forward_inputs = make_forward_inputs(batch)
            maybe_sync(device)
            forward_start = time.perf_counter()
            _ = model(**forward_inputs)
            maybe_sync(device)
            forward_end = time.perf_counter()
            e2e_end = time.perf_counter()

            batch_size = int(batch["labels"].shape[0])
            forward_ms = (forward_end - forward_start) * 1000.0
            e2e_ms = (e2e_end - e2e_start) * 1000.0

            forward_batch_latency_ms.append(forward_ms)
            e2e_batch_latency_ms.append(e2e_ms)
            per_sample_forward_ms.append(forward_ms / max(batch_size, 1))
            total_samples += batch_size
            total_e2e_seconds += max(e2e_end - e2e_start, 0.0)
            batches_measured += 1

    return {
        "num_batches_measured": batches_measured,
        "num_samples_measured": total_samples,
        "forward_batch_latency_ms": summarize_ms(forward_batch_latency_ms),
        "e2e_batch_latency_ms": summarize_ms(e2e_batch_latency_ms),
        "forward_sample_latency_mean_ms": float(statistics.mean(per_sample_forward_ms))
        if per_sample_forward_ms
        else float("nan"),
        "eval_samples_per_sec": float(total_samples / total_e2e_seconds)
        if total_e2e_seconds > 0
        else float("nan"),
        "cuda_memory_peak": current_cuda_memory(device),
    }


def safe_format(value: Optional[float]) -> str:
    if value is None:
        return "N/A"
    if isinstance(value, float) and (math.isnan(value) or math.isinf(value)):
        return "N/A"
    return f"{value:.4f}"


